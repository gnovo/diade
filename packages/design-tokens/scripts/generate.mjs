// Generates platform outputs from tokens.json (the Díade design system source).
// Run: pnpm --filter @diade/design-tokens generate
//
// Outputs:
//   src/generated.ts        typed theme for React Native (light + dark colours, type, space, radius, shadows)
//   ../../apps/mobile/global.css  CSS custom properties consumed by NativeWind / Tailwind
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const tokens = JSON.parse(readFileSync(resolve(root, 'tokens.json'), 'utf8'));

const px = (v) => Number(String(v).replace('px', ''));
const em = (v, size) =>
  String(v).endsWith('em') ? Number(String(v).replace('em', '')) * size : px(v);
const pick = (value, theme) => (typeof value === 'string' ? value : value[theme]);
const kebabToCamel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

// Colours ------------------------------------------------------------------
const colorNames = tokens.color.tokens.map((t) => t.name);
const colorsFor = (theme) =>
  Object.fromEntries(tokens.color.tokens.map((t) => [t.name, pick(t.value, theme)]));
const colorsLight = colorsFor('light');
const colorsDark = colorsFor('dark');

// Spacing, radius, sizes ----------------------------------------------------
const spacing = Object.fromEntries(tokens.spacing.tokens.map((t) => [t.name, px(t.value)]));
const radius = Object.fromEntries(tokens.radius.tokens.map((t) => [t.name, px(t.value)]));
const sizes = Object.fromEntries(
  [...tokens.size.tokens, ...tokens.opacity.tokens.map((t) => ({ ...t, value: t.value }))].map(
    (t) => [t.name, t.name.startsWith('opacity') ? Number(t.value) : px(t.value)],
  ),
);

// Typography ----------------------------------------------------------------
// Font family is chosen from the weight so Android (which has one file per weight) picks the right face.
const familyForWeight = {
  400: 'PlusJakartaSans_400Regular',
  500: 'PlusJakartaSans_500Medium',
  600: 'PlusJakartaSans_600SemiBold',
  700: 'PlusJakartaSans_700Bold',
};
const typography = {};
for (const group of tokens.type.groups) {
  for (const style of group.styles) {
    const size = px(style.fontSize);
    typography[style.name] = {
      fontSize: size,
      lineHeight: px(style.lineHeight),
      letterSpacing: style.letterSpacing ? em(style.letterSpacing, size) : 0,
      fontWeight: style.fontWeight,
      fontFamily: familyForWeight[style.fontWeight],
    };
  }
}

// Shadows: parse the first layer of each CSS box-shadow into React Native shadow props.
function parseShadow(css) {
  const first = css.split(/,(?![^(]*\))/)[0].trim();
  const m = first.match(/^(-?[\d.]+)(?:px)?\s+(-?[\d.]+)px\s+([\d.]+)px\s+(rgba\([^)]+\))/);
  if (!m) throw new Error(`Unparsed shadow: ${css}`);
  const [, , y, blur, color] = m;
  const alpha = Number(color.split(',')[3].replace(')', '').trim());
  return {
    shadowColor: color.replace(/,\s*[\d.]+\)$/, ')').replace('rgba(', 'rgb('),
    shadowOffset: { width: 0, height: Number(y) },
    shadowOpacity: alpha,
    shadowRadius: Number(blur) / 2,
    // Android elevation approximates the blur radius.
    elevation: Math.round(Number(blur) / 2),
  };
}
const shadows = { light: {}, dark: {} };
for (const t of tokens.shadow.tokens) {
  const key = kebabToCamel(t.name);
  shadows.light[key] = parseShadow(t.value.light);
  shadows.dark[key] = parseShadow(t.value.dark);
}

// Emit TypeScript -----------------------------------------------------------
const header =
  '// GENERATED by packages/design-tokens/scripts/generate.mjs from tokens.json. Do not edit by hand.\n';
const ts = `${header}
export const colorsLight = ${JSON.stringify(colorsLight, null, 2)} as const;
export const colorsDark = ${JSON.stringify(colorsDark, null, 2)} as const;
export type ColorToken = keyof typeof colorsLight;
export const colorNames = ${JSON.stringify(colorNames)} as const;

export const space = ${JSON.stringify(
  Object.fromEntries(Object.entries(spacing).map(([k, v]) => [k.replace('space-', ''), v])),
  null,
  2,
)} as const;

export const radius = ${JSON.stringify(
  Object.fromEntries(Object.entries(radius).map(([k, v]) => [k.replace('radius-', ''), v])),
  null,
  2,
)} as const;

export const sizes = ${JSON.stringify(sizes, null, 2)} as const;

export const typography = ${JSON.stringify(typography, null, 2)} as const;
export type TypographyStyle = keyof typeof typography;

export const shadows = ${JSON.stringify(shadows, null, 2)} as const;
`;
writeFileSync(resolve(root, 'src/generated.ts'), ts);

// Emit CSS custom properties for NativeWind ----------------------------------
const cssVars = (colors) =>
  colorNames.map((name) => `  --color-${name}: ${colors[name]};`).join('\n');
const css = `${header.replace('//', '/*').replace(/\n$/, ' */')}
@tailwind base;
@tailwind components;
@tailwind utilities;

:root {
${cssVars(colorsLight)}
}

@media (prefers-color-scheme: dark) {
  :root {
${cssVars(colorsDark)}
  }
}
`;
writeFileSync(resolve(root, '../../apps/mobile/global.css'), css);

// Tailwind reads this JSON directly (tailwind.config.js is CommonJS).
writeFileSync(
  resolve(root, 'src/tailwind-tokens.json'),
  `${JSON.stringify(
    {
      colorNames,
      fontSizes: typography,
      // Unprefixed keys (sm, md, ...) so tailwind.config.js can read them directly.
      spacing: Object.fromEntries(
        Object.entries(spacing).map(([k, v]) => [k.replace('space-', ''), v]),
      ),
      radius: Object.fromEntries(
        Object.entries(radius).map(([k, v]) => [k.replace('radius-', ''), v]),
      ),
    },
    null,
    2,
  )}\n`,
);

console.log(
  `Generated ${colorNames.length} colours, ${Object.keys(typography).length} type styles, ${Object.keys(shadows.light).length} shadows.`,
);

// Logo artwork ---------------------------------------------------------------
// The SVGs in ../brand are master artwork (never redraw). Their brand colours are swapped for
// placeholders here so the app can recolour them per theme at runtime.
const brandColourMap = {
  '#0D4F46': '{{logo-ink}}', // left D and wordmark
  '#65C5B3': '{{brand-mint}}', // right D
  '#2E9C88': '{{brand-overlap}}', // overlap
};
const readBrand = (file) => {
  let svg = readFileSync(resolve(root, 'brand', file), 'utf8');
  for (const [hex, placeholder] of Object.entries(brandColourMap)) {
    svg = svg.split(`"${hex}"`).join(`"${placeholder}"`);
  }
  return svg
    .replace(/<title>[^<]*<\/title>/, '')
    .replace(/\s+/g, ' ')
    .trim();
};
const logos = {
  lockup: readBrand('diade-lockup.svg'),
  stacked: readBrand('diade-lockup-stacked.svg'),
  mark: readBrand('diade-mark.svg'),
  wordmark: readBrand('diade-wordmark.svg'),
};
const logoTs = `${header}
/** Brand artwork with colour placeholders: {{logo-ink}}, {{brand-mint}}, {{brand-overlap}}. */
export const logoSvg = ${JSON.stringify(logos, null, 2)} as const;
`;
writeFileSync(resolve(root, 'src/logo.generated.ts'), logoTs);

// Díade's custom Memories icon (not Lucide). Stroke colour becomes a {{ink}} placeholder.
const memory = readFileSync(resolve(root, 'brand', 'memory.svg'), 'utf8')
  .replace(/<title>[^<]*<\/title>/, '')
  .split('stroke="#0F1F1C"')
  .join('stroke="{{ink}}"')
  .replace(/\s+/g, ' ')
  .trim();
writeFileSync(
  resolve(root, 'src/logo.generated.ts'),
  logoTs +
    `\n/** Memories icon, stroke placeholder {{ink}}. */\nexport const memoryIconSvg = ${JSON.stringify(memory)} as const;\n`,
);
